// The layout as a keyboard-layout bundle, the form macOS needs to show an
// icon for it and to know its language. Like the .keylayout inside it, the
// bundle is data, not code: no signing, no notarisation.
//
// macOS reads the settings from Info.plist under "KLInfo_" + the layout's
// name (HIToolbox: islPopulateKLPropertiesFromBundle). Of the keys there it
// knows, three are used: the input source id, the intended language, and
// whether the icon is a template. The icon is found by name: the .keylayout's
// file name with .icns (TN2056).
import { DOWNLOADS, LAYOUT_NAME, MAC_BUNDLE } from '../keys.js'
import { generateKeylayout } from './keylayout.js'
import { encodeIcns } from './icon.js'
import { zip } from '../zip.js'

/** Fixed once, never changed: macOS remembers an enabled layout by this id, so
 * changing it would drop the layout from every Mac it is enabled on. */
export const MAC_INPUT_SOURCE_ID = 'uz.alfavit.keylayout.Ozbek-yangi-alifbo'
const BUNDLE_ID = 'uz.alfavit.keyboardlayout.Ozbek-yangi-alifbo'

/** BCP 47, as Apple's own Uzbek layouts say uz-Cyrl and uz-Arab. */
const INTENDED_LANGUAGE = 'uz-Latn'

const xmlText = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

export function generateInfoPlist(): string {
  const entry = (key: string, value: string) => `\t<key>${xmlText(key)}</key>\n\t${value}`
  const string = (s: string) => `<string>${xmlText(s)}</string>`
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by packages/layouts: run its generate script. Do not edit by hand. -->
<plist version="1.0">
<dict>
${entry('CFBundleIdentifier', string(BUNDLE_ID))}
${entry('CFBundleName', string(LAYOUT_NAME))}
${entry('CFBundlePackageType', string('BNDL'))}
${entry('CFBundleShortVersionString', string('1.0'))}
${entry('CFBundleVersion', string('1'))}
${entry(`KLInfo_${LAYOUT_NAME}`, `<dict>
\t\t<key>TISInputSourceID</key>
\t\t${string(MAC_INPUT_SOURCE_ID)}
\t\t<key>TISIntendedLanguage</key>
\t\t${string(INTENDED_LANGUAGE)}
\t\t<key>TISIconIsTemplate</key>
\t\t<true/>
\t</dict>`)}
</dict>
</plist>
`
}

export function macBundleFiles(): { path: string; content: string | Buffer }[] {
  const resources = `${MAC_BUNDLE}/Contents/Resources`
  return [
    { path: `${MAC_BUNDLE}/Contents/Info.plist`, content: generateInfoPlist() },
    { path: `${resources}/${DOWNLOADS.macKeylayout.replace(/\.keylayout$/, '.icns')}`, content: encodeIcns() },
    { path: `${resources}/${DOWNLOADS.macKeylayout}`, content: generateKeylayout() },
  ]
}

export function macBundleZip(): Buffer {
  return zip(macBundleFiles())
}

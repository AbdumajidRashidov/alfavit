// macModel() → a .keylayout file macOS loads from ~/Library/Keyboard Layouts.
// The file is data, not code: no signing, no notarisation.
import { LAYOUT_NAME } from '../keys.js'
import { macModel, MAC_STATES, type MacState, type MacOutput, type DeadKeyId } from './model.js'

/** Fixed once, never reused: macOS identifies the layout by group + id. */
export const MAC_LAYOUT_ID = -19263

export const MAC_STATE_INDEX: Record<MacState, number> = Object.fromEntries(MAC_STATES.map((s, i) => [s, i])) as Record<MacState, number>

/** UCKeyTranslate's modifier bits, also used for the combination table. */
const CMD = 1, SHIFT = 2, CAPS = 4, OPT = 8, CTRL = 16

/** The state each modifier combination selects, as on Apple's U.S. layout
 * (checked for all 32 by tools/compare-us.swift): Control wins over
 * everything; ⌘ alone ignores Shift and Caps Lock; ⌘⌥ is the Option layer
 * without accents, ⌘⇧⌥ the Shift+Option one. */
function stateFor(bits: number): MacState {
  if (bits & CTRL) return 'control'
  if (bits & CMD) return bits & OPT ? (bits & SHIFT ? 'shiftOption' : 'commandOption') : 'command'
  if (bits & OPT) return bits & SHIFT ? 'shiftOption' : bits & CAPS ? 'capsOption' : 'option'
  return bits & SHIFT ? 'shift' : bits & CAPS ? 'caps' : 'plain'
}

export interface MacCombo { bits: number; state: MacState }
export const MAC_COMBOS: MacCombo[] = Array.from({ length: 32 }, (_, bits) => ({ bits, state: stateFor(bits) }))

/** One exact combination, no wildcards: a modifier not named must be up. */
const modifierKeys = (bits: number) =>
  [bits & SHIFT && 'anyShift', bits & CAPS && 'caps', bits & OPT && 'anyOption', bits & CTRL && 'anyControl', bits & CMD && 'command']
    .filter(Boolean)
    .join(' ')

/** Every output that is not an ASCII letter or digit becomes a character
 * reference, so control characters and quotes can never break the XML. */
function esc(s: string): string {
  return [...s].map((c) => (/[A-Za-z0-9]/.test(c) ? c : `&#x${c.codePointAt(0)!.toString(16).toUpperCase().padStart(4, '0')};`)).join('')
}

export function generateKeylayout(): string {
  const { keys, deadKeys } = macModel()
  const deadIds = Object.keys(deadKeys) as DeadKeyId[]

  // Characters that compose with a dead key (plus space, which turns a dead
  // key into its spacing accent) are typed through actions; the rest are
  // plain outputs. A plain output pressed in a dead state emits the
  // terminator and then itself — so ⌥e then ⌥s gives ´ş with no extra rule.
  const composing = new Set<string>([' ', ...deadIds.flatMap((d) => Object.keys(deadKeys[d].compose))])
  const actionId = (ch: string) => (ch === ' ' ? 'space' : `c${ch.codePointAt(0)!.toString(16)}`)

  const keyLine = (code: number, out: MacOutput) => {
    if (typeof out !== 'string') return `<key code="${code}" action="dead-${out.dead}"/>`
    if (composing.has(out)) return `<key code="${code}" action="${actionId(out)}"/>`
    return `<key code="${code}" output="${esc(out)}"/>`
  }

  const codes = Object.keys(keys).map(Number).sort((a, b) => a - b)
  const keyMaps = MAC_STATES.map((state) => {
    const lines = codes.map((code) => `      ${keyLine(code, keys[code][state])}`)
    return `    <keyMap index="${MAC_STATE_INDEX[state]}">\n${lines.join('\n')}\n    </keyMap>`
  })

  const selects = MAC_STATES.map((state) => {
    const mods = MAC_COMBOS.filter((c) => c.state === state).map((c) => `      <modifier keys="${modifierKeys(c.bits)}"/>`).join('\n')
    return `    <keyMapSelect mapIndex="${MAC_STATE_INDEX[state]}">\n${mods}\n    </keyMapSelect>`
  })

  const deadActions = deadIds.map((d) => `    <action id="dead-${d}">\n      <when state="none" next="${d}"/>\n    </action>`)
  const charActions = [...composing].sort().map((ch) => {
    const whens = [`      <when state="none" output="${esc(ch)}"/>`]
    for (const d of deadIds) {
      const out = ch === ' ' ? deadKeys[d].terminator : deadKeys[d].compose[ch]
      if (out) whens.push(`      <when state="${d}" output="${esc(out)}"/>`)
    }
    return `    <action id="${actionId(ch)}">\n${whens.join('\n')}\n    </action>`
  })
  const terminators = deadIds.map((d) => `    <when state="${d}" output="${esc(deadKeys[d].terminator)}"/>`)

  // macOS truncates any output longer than maxout (UTF-16 units); ⌥e then j
  // types j + U+0301, so this is computed rather than assumed to be 1.
  const allOutputs = [
    ...codes.flatMap((c) => MAC_STATES.map((s) => keys[c][s]).filter((o): o is string => typeof o === 'string')),
    ...deadIds.flatMap((d) => [deadKeys[d].terminator, ...Object.values(deadKeys[d].compose)]),
  ]
  const maxout = Math.max(...allOutputs.map((o) => o.length))

  return `<?xml version="1.1" encoding="UTF-8"?>
<!DOCTYPE keyboard SYSTEM "file://localhost/System/Library/DTDs/KeyboardLayout.dtd">
<!-- Generated by packages/layouts: run its generate script. Do not edit by hand. -->
<keyboard group="126" id="${MAC_LAYOUT_ID}" name="${LAYOUT_NAME}" maxout="${maxout}">
  <layouts>
    <layout first="0" last="254" mapSet="ansi" modifiers="mods"/>
  </layouts>
  <modifierMap id="mods" defaultIndex="0">
${selects.join('\n')}
  </modifierMap>
  <keyMapSet id="ansi">
${keyMaps.join('\n')}
  </keyMapSet>
  <actions>
${[...deadActions, ...charActions].join('\n')}
  </actions>
  <terminators>
${terminators.join('\n')}
  </terminators>
</keyboard>
`
}

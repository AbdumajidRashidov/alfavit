// Renders the layout's menu-bar icon the way macOS draws its own input-source
// badges ("A", "РУ", "ЎЗ"), and writes the pixels to src/macos/iconMasks.ts
// for the generator. macOS only; run it after changing the icon:
//
//   swift packages/layouts/tools/render-icon.swift
//
// The drawing is KeyboardLayouts.framework's (KLInputSourceIconManager), done
// with public calls: a rounded rectangle of radius 5 pt, the label cut out of
// it in the system font, semibold, 11 pt, its line box centred vertically and
// its ink centred across. Checked on macOS 27.0 against Apple's own renderer
// asked for a 16 × 16 pt "öz" badge: no pixel off by more than 7/255.
//
// The only difference from ABC's badge is the width. macOS draws a
// third-party layout's icon at 16 × 16 pt; Apple's badges are 22 × 16 pt.
import AppKit

let label = "öz"
let sizes = [16, 32, 64] // pixels: 16 pt at 1x, 16 pt at 2x and 32 pt at 1x, 32 pt at 2x

/** Alpha, one byte per pixel, rows top to bottom. */
func mask(px: Int) -> [UInt8] {
  let ctx = CGContext(data: nil, width: px, height: px, bitsPerComponent: 8, bytesPerRow: px, space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.alphaOnly.rawValue)!
  ctx.scaleBy(x: CGFloat(px) / 16, y: CGFloat(px) / 16)
  ctx.addPath(CGPath(roundedRect: CGRect(x: 0, y: 0, width: 16, height: 16), cornerWidth: 5, cornerHeight: 5, transform: nil))
  ctx.fillPath()
  let font = NSFont.systemFont(ofSize: 11, weight: .semibold)
  let line = CTLineCreateWithAttributedString(NSAttributedString(string: label, attributes: [.font: font]))
  var ascent: CGFloat = 0, descent: CGFloat = 0
  _ = CTLineGetTypographicBounds(line, &ascent, &descent, nil)
  let ink = CTLineGetImageBounds(line, ctx)
  ctx.setBlendMode(.destinationOut)
  ctx.textPosition = CGPoint(x: 8 - (ink.minX + ink.width / 2), y: 8 - (ascent - descent) / 2)
  CTLineDraw(line, ctx)
  let data = ctx.data!.bindMemory(to: UInt8.self, capacity: px * px)
  return (0..<px * px).map { data[$0] }
}

let entries = sizes.map { px in "  \(px): '\(Data(mask(px: px)).base64EncodedString())'," }
let source = """
// Generated by tools/render-icon.swift on macOS. Do not edit by hand: run the
// tool after changing the icon, then the generate script.
//
// "\(label)" cut out of a rounded badge, drawn as macOS draws its own
// input-source badges, in Apple's system font (SF). Pixels only, no font data;
// shown only by macOS, beside Apple's own badges in the same typeface.
// Alpha masks, one byte per pixel, rows top to bottom, base64, by pixel size.
export const ICON_LABEL = '\(label)'

export const ICON_MASKS: Record<number, string> = {
\(entries.joined(separator: "\n"))
}

"""
let out = URL(fileURLWithPath: #filePath).deletingLastPathComponent().appendingPathComponent("../src/macos/iconMasks.ts").standardized
try! source.write(to: out, atomically: true, encoding: .utf8)
print("wrote \(out.path)")
